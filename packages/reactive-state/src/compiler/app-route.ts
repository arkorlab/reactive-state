import { existsSync, lstatSync, readFileSync } from 'node:fs';
import path from 'node:path';

import { COMPILE_ROUTE_DIRECTORY, dynamicSegmentOf } from '../routing.ts';
import { PAGE_EXTENSIONS } from './page-extensions.ts';
import { pagesRoutesOf } from './pages-routes.ts';
import { isPrivate, scanApp } from './route-scan.ts';

/**
 * What the compile writes into the application rather than its own output directory — the route
 * every path under `/api/reactive-state/` is served by, `<app>/api/reactive-state/[...path]/route.ts`
 * — and what tells each file a compile writes apart from the application's own: what it opens with.
 * A file of the application's is never written over, nor taken away: the compile refuses one that
 * stands where its route goes, or is served where its route serves.
 */

/** What every file a compile writes opens with: what tells one apart from the application's. */
export const GENERATED = '// Generated by @arkorlab/reactive-state';

/** The compile's route in an `app` directory, under it, by its segments. */
const ROUTE: readonly string[] = [...COMPILE_ROUTE_DIRECTORY.split('/'), 'route.ts'];

/** The path the compile's route serves every path under, by its segments: those above its catch-all. */
const SERVED: readonly string[] = COMPILE_ROUTE_DIRECTORY.split('/').filter(
  (segment) => dynamicSegmentOf(segment) === undefined,
);

/** The names Next.js reads an application's proxy by: `proxy`, and `middleware`, its older name. */
const PROXY_NAMES: readonly string[] = ['proxy', 'middleware'];

/**
 * The application's proxy — `proxy.ts`, or `middleware.ts` by its older name — where it has one: a
 * file of a page's extension in the directory the `app` directory is in, where Next.js reads one
 * (`rootDir`, as it builds). It runs ahead of every route, and may change any response.
 */
export function proxyOf(appDir: string): string | undefined {
  const directory = path.dirname(appDir);
  return PROXY_NAMES.flatMap((name) =>
    PAGE_EXTENSIONS.map((extension) => path.join(directory, `${name}.${extension}`)),
  ).find((file) => existsSync(file));
}

/** The compile's route in the `app` directory `appDir`, by its path. */
export function appRouteOf(appDir: string): string {
  return path.join(appDir, ...ROUTE);
}

/**
 * Whether `file` is one a compile wrote: a file — no link, nor what is not there — that opens as
 * every file a compile writes does (`GENERATED`).
 */
export function isGeneratedFile(file: string): boolean {
  try {
    if (!lstatSync(file).isFile()) {
      return false;
    }
    return readFileSync(file).subarray(0, GENERATED.length).toString('utf8') === GENERATED;
  } catch {
    return false;
  }
}

/** A file of the application's that the compile's route would write over, or be served beside. */
export interface RouteCollision {
  readonly file: string;
  readonly reason: string;
}

const OWNED =
  "A file of the application's stands where the compile writes the route every path under `/api/reactive-state/` is served by — the event streams, the sign-in, the routes under middleware — which a build would write over: it does not open as what the compile writes. Move it, and what it serves, from under `/api/reactive-state/`.";

const SHADOWED =
  "A route of the application's is served under `/api/reactive-state/`, every path of which the compile's route (`api/reactive-state/[...path]/route.ts`) serves: one would answer in the other's place. Move it from under `/api/reactive-state/`.";

const OVERLAPPED =
  "A route of the application's may be served at a path under `/api/reactive-state/` — a dynamic segment of it, or a catch-all, stands where a segment of that path is — every one of which the compile's route (`api/reactive-state/[...path]/route.ts`) serves, and Next.js matches first there: the route would never answer those. Give it a static segment where its dynamic one is, or a path under no `/api/reactive-state/`.";

/** Whether a segment is a route group's, `(marketing)`, which names no part of a path. */
function isGroupSegment(segment: string): boolean {
  return segment.startsWith('(') && segment.endsWith(')');
}

/**
 * Why a route of `served` segments — its path as Next.js serves it — collides with the compile's
 * route, which serves every path under `/api/reactive-state/`, one segment at least: written under
 * it, segment for segment (`SHADOWED`); or able to be served there through a dynamic segment or a
 * catch-all of its own where it writes a segment of that path at its place as well
 * (`OVERLAPPED`) — `api/[namespace]/custom` serves `/api/reactive-state/custom`, which the compile's
 * route takes. None for a route that writes none of those segments: `/[section]/[id]/[part]` is a
 * path of any three segments, and Next.js serves it at none it has a route of more segments written
 * for, the compile's route's among them.
 */
function collisionOf(served: readonly string[]): string | undefined {
  let written = 0;
  for (const [at, segment] of SERVED.entries()) {
    const given = served[at];
    const kind = given === undefined ? undefined : dynamicSegmentOf(given)?.kind;
    if (given === undefined || (kind === undefined && given !== segment)) {
      return undefined;
    }
    if (kind === 'catchall' || kind === 'optional-catchall') {
      return written > 0 ? OVERLAPPED : undefined;
    }
    written += kind === undefined ? 1 : 0;
  }
  if (written === 0 || served.length <= SERVED.length) {
    return undefined;
  }
  return written === SERVED.length ? SHADOWED : OVERLAPPED;
}

/**
 * Why a page or a route handler in `directory` — its path under the `app` directory — collides with
 * the compile's route (`collisionOf`): its segments as Next.js serves them, route groups and slots
 * left out; none of a private folder's.
 */
function appCollisionOf(directory: string): string | undefined {
  if (isPrivate(directory)) {
    return undefined;
  }
  return collisionOf(
    directory.split('/').filter((segment) => !isGroupSegment(segment) && !segment.startsWith('@')),
  );
}

/**
 * The Pages Router's routes that collide with the compile's route (`collisionOf`), with why: each
 * route of `pages` beside `app` (`pagesRoutesOf`).
 */
function pagesCollisions(appDir: string): readonly RouteCollision[] {
  return pagesRoutesOf(appDir).flatMap(({ file, segments }) => {
    const reason = collisionOf(segments);
    return reason === undefined ? [] : [{ file, reason }];
  });
}

/**
 * The application's own files the compile's route would write over, or be served beside: a file
 * where the route goes that is no compile's (`isGeneratedFile`), and each other page and route
 * handler of the `app` directory, and each route of the Pages Router, that may be served under
 * `/api/reactive-state/` (`collisionOf`). Nothing of `outDir`, nor of what the walk of the app
 * leaves alone (`scanApp`).
 */
export function routeCollisions(appDir: string, outDir: string): readonly RouteCollision[] {
  const own = appRouteOf(appDir);
  const { handlers, pages } = scanApp(appDir, outDir);
  const fromApp = [...pages, ...handlers].flatMap((entry): RouteCollision[] => {
    if (entry.file === own) {
      return isGeneratedFile(own) ? [] : [{ file: own, reason: OWNED }];
    }
    const reason = appCollisionOf(entry.directory);
    return reason === undefined ? [] : [{ file: entry.file, reason }];
  });
  return [...fromApp, ...pagesCollisions(appDir)];
}
