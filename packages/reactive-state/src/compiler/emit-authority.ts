/**
 * A component's program for the authority (`<id>.authority.mts`): no JSX, so that Node runs it with
 * its types stripped and a Durable Object's bundle holds no React. `evaluate` runs the server part
 * as the component wrote it, its JSX rendered by `$.h`, and answers what it renders — or, for a
 * component with state, its client part: the props the browser reads, what the authority evaluates
 * for each state, the slots it renders, and its dynamic sites — each the local states it reads, the
 * guard of the conditions it stands under, and its element, rendered of those states. Its updaters
 * are what a write may run, by id.
 */

/** The widest an object literal is written on one line, past which its entries go one to a line. */
const WIDTH = 100;

/** How deep the body of an update is written: within its entry of `updaters`. */
const UPDATE_DEPTH = 4;
const UPDATE_INDENT = ' '.repeat(UPDATE_DEPTH);

/** The module a program's helpers and types are imported from. */
const PROGRAM = '@arkorlab/reactive-state/program';

/** The comment each output opens with. */
export function header(source: string, what = 'component'): string {
  return `// Generated by @arkorlab/reactive-state from ${source}. Do not edit: change the ${what} and compile it again.`;
}

export interface AuthorityInput {
  readonly component: Component;
  readonly sides: Sides;
  readonly buildId: string;
  /** The updaters the component writes with, its own and its hooks', by id. */
  readonly updaters: ReadonlyMap<string, Registered>;
  /** The keys whose setter the component, or a hook it calls, uses, in the order the states are. */
  readonly writable: readonly string[];
  /** The names the props' annotation reads, which each output that copies it imports. */
  readonly propTypes: ReadonlySet<string>;
}

/** The modules the authority renders, or binds, by reference, which a program imports none of. */
const BY_REFERENCE: ReadonlySet<ModuleKind> = new Set([
  'client',
  'component',
  'element',
  'operations',
]);

/** The names a program declares itself, which an import it writes for an update may not take. */
const OWN_NAMES: ReadonlySet<string> = new Set([
  'actionRef',
  'buildId',
  'component',
  'componentRef',
  'evaluate',
  'moduleRef',
  'ProgramUpdater',
  'protocolVersion',
  'RenderScope',
  'States',
  'StatesOf',
  'updaters',
  'writable',
]);

/**
 * The imports a program writes: what its code reads of the component's imports — at run time, or in
 * a type — and what its updates read of the application's shared modules, a hook's among them,
 * each under a name of its own.
 */
class ImportPlan {
  readonly #lines: ImportLine[] = [];
  /** The program's own names, and each one it imports, by the import that takes it. */
  readonly #taken = new Map<string, string>();

  constructor(input: AuthorityInput) {
    const { component, propTypes, sides, updaters } = input;
    for (const name of OWN_NAMES) {
      this.#taken.set(name, '');
    }
    // The component's own names, which a site's function holds its inputs by and the server part
    // declares: an import a site's value is computed by takes none of them.
    for (const [name, entry] of component.names) {
      if (entry.kind !== 'import') {
        this.#taken.set(name, '');
      }
    }
    // What the code written into a site's function declares, or reads as a global (`derive.ts`), and
    // what the updates read as globals, which the program writes as they are.
    for (const name of reservedNames(sides.derivation.taken, updaters)) {
      this.#taken.set(name, '');
    }
    const { refs } = sides;
    const bindings = component.modules.flatMap((module) => module.bindings);
    for (const binding of bindings) {
      const name = binding.name.text;
      if (refs.components.has(name) || refs.modules.has(name) || refs.actions.has(name)) {
        this.#taken.set(name, '');
        continue;
      }
      const byReference = BY_REFERENCE.has(binding.module.target.kind);
      const value = !byReference && !binding.typeOnly && sides.authority.values.has(name);
      if (value || sides.authority.types.has(name) || propTypes.has(name)) {
        this.#add(binding, !value);
      }
    }
  }

  #add(binding: ImportBinding, typeOnly: boolean, local = binding.name.text): void {
    if (!this.#taken.has(local)) {
      this.#taken.set(local, identityOf(binding));
    }
    this.#lines.push({
      binding,
      from: binding.module.written,
      typeOnly,
      ...(local !== binding.name.text && { local }),
    });
  }

  /** An import with a name available in derived code, reused only for compatible type/value reads. */
  #require(binding: ImportBinding, typeOnly: boolean): string {
    const identity = identityOf(binding);
    const existing = this.#lines.find((line) => {
      return (
        (typeOnly || !line.typeOnly) &&
        identityOf(line.binding) === identity &&
        this.#taken.get(line.local ?? line.binding.name.text) === identity
      );
    });
    if (existing !== undefined) {
      return existing.local ?? existing.binding.name.text;
    }
    const name = unusedName(binding.name.text, (each) => {
      const taker = this.#taken.get(each);
      return taker !== undefined && taker !== identity;
    });
    this.#add(binding, typeOnly, name);
    return name;
  }

  /** The name the program reads `binding`, a shared module's import, by: its own, or another. */
  require(binding: ImportBinding): string {
    return this.#require(binding, false);
  }

  /** The name the program reads `binding`, an import of a type a hook's module imports, by. */
  requireType(binding: ImportBinding): string {
    return this.#require(binding, true);
  }

  declarations(): readonly string[] {
    return importDeclarations(this.#lines);
  }
}

/** What an import is, whatever it is named: its module, as written, and its export. */
function identityOf(binding: ImportBinding): string {
  return `${binding.module.written}#${binding.exported}`;
}

export function emitAuthority(input: AuthorityInput): string {
  const { component, sides } = input;
  const { refs } = sides;
  const stateful = component.returned !== undefined;
  const lines = new ImportPlan(input);
  const updaterLines = updaterEntries(input, lines);
  const values = [
    refs.components.size > 0 ? 'componentRef' : undefined,
    refs.modules.size > 0 ? 'moduleRef' : undefined,
    refs.actions.size > 0 ? 'actionRef' : undefined,
  ].filter((helper) => helper !== undefined);
  const types = [
    input.updaters.size > 0 ? 'ProgramUpdater' : undefined,
    'RenderScope',
    stateful ? 'StatesOf' : undefined,
  ].filter((helper) => helper !== undefined);
  const consts = component.modules.flatMap((module) =>
    module.bindings.flatMap((binding) => refConst(binding, sides)),
  );
  const usesScope = stateful || renders(component.server);
  // Before the imports are declared: what the sites' values are computed by imports its own.
  const body = bodyOf(input, lines);
  return [
    header(`${component.id}.reactive.tsx`),
    programImport(values, types),
    ...lines.declarations(),
    '',
    `export const protocolVersion = ${String(PROTOCOL_VERSION)};`,
    `export const buildId = ${literal(input.buildId)};`,
    `export const component = ${literal(component.id)};`,
    ...consts,
    '',
    `export ${component.isAsync ? 'async ' : ''}function evaluate(${propsParameter(input)}, ${usesScope ? '$' : '_$'}: RenderScope) {`,
    ...body,
    '}',
    '',
    ...(stateful ? ['export type States = StatesOf<typeof evaluate>;'] : []),
    `export const writable = Object.freeze([${input.writable.map((key) => literal(key)).join(', ')}]);`,
    input.updaters.size === 0
      ? 'export const updaters = Object.freeze({});'
      : [
          'export const updaters = Object.freeze({',
          ...updaterLines.map((line) => `  ${line}`),
          '} satisfies Readonly<Record<string, ProgramUpdater>>);',
        ].join('\n'),
    '',
  ].join('\n');
}

/** The import of the framework's helpers a program uses: its values, and its types as types. */
function programImport(values: readonly string[], types: readonly string[]): string {
  if (values.length === 0) {
    return `import type { ${types.join(', ')} } from '${PROGRAM}';`;
  }
  const named = [...values, ...types.map((type) => `type ${type}`)];
  return `import { ${named.join(', ')} } from '${PROGRAM}';`;
}

/** Whether the server part holds JSX, which it renders with `$`. */
function renders(statements: readonly Statement[]): boolean {
  let found = false;
  const visit = (node: Node): void => {
    found ||= isJsx(node);
    if (!found) {
      node.forEachChild(visit);
    }
  };
  for (const statement of statements) {
    visit(statement);
  }
  return found;
}

/** The constant a reference the authority renders or binds by is declared as. */
function refConst(binding: ImportBinding, sides: Sides): readonly string[] {
  const name = binding.name.text;
  const component = sides.refs.components.get(name);
  if (component !== undefined) {
    return [`const ${name} = componentRef(${literal(component)});`];
  }
  const module = sides.refs.modules.get(name);
  if (module !== undefined) {
    return [`const ${name} = moduleRef(${literal(module.module)}, ${literal(module.name)});`];
  }
  const action = sides.refs.actions.get(name);
  return action === undefined
    ? []
    : [`const ${name} = actionRef(${literal(action.module)}, ${literal(action.name)});`];
}

/** `evaluate`'s props: the ones the program reads, destructured, typed as the component types them. */
function propsParameter(input: AuthorityInput): string {
  const { component, sides } = input;
  const { parameter, propsType, sourceFile } = component;
  if (parameter === undefined) {
    return '_props: Readonly<Record<string, unknown>>';
  }
  const read = component.props.filter(
    (prop) => reads(sides.authority, prop.local.text) || reads(sides.browser, prop.local.text),
  );
  const pattern = `{ ${read.map((prop) => prop.element.getText(sourceFile)).join(', ')} }`.replace(
    '{  }',
    '{}',
  );
  return propsType === undefined ? pattern : `${pattern}: ${propsType.getText(sourceFile)}`;
}

/** What `evaluate` runs: the server part, then — for a component with state — its client part. */
function bodyOf(input: AuthorityInput, plan: ImportPlan): readonly string[] {
  const { component, sides } = input;
  const { sourceFile } = component;
  const rewrite = renderingRewrite(component);
  const server = component.server
    .map((statement) => splicedFrom(statement, statement.pos, sourceFile, rewrite))
    .join('')
    .replace(/^\n+/u, '');
  const lines = server === '' ? [] : [server];
  if (component.returned === undefined) {
    return lines;
  }
  const first = component.states[0]?.statement ?? component.returned;
  const indent = indentAt(sourceFile.text, first.getStart(sourceFile));
  const inner = `${indent}  `;
  const props = component.props
    .filter((prop) => reads(sides.browser, prop.local.text))
    .map((prop) => {
      if (prop.name === '__proto__') {
        return `[${literal(prop.name)}]: ${prop.local.text}`;
      }
      return prop.name === prop.local.text
        ? prop.name
        : `${propertyName(prop.name)}: ${prop.local.text}`;
    });
  const writing = { rewrite, sourceFile };
  const states = sides.evaluated.map((state) => {
    const start = moved(state.input, inner, writing);
    const value =
      state.type === undefined ? start : `${operand(state.input, start)} as ${state.type}`;
    return `${propertyName(state.key)}: ${value}`;
  });
  const slots = sides.slots.map((slot) => `${slot.name}: ${moved(slot.unit, inner, writing)}`);
  const siteWriting: SiteWriting = {
    component,
    derivation: sides.derivation,
    imports: sides.derivation.imports.map((binding) => plan.require(binding)),
    lines: plan,
  };
  const sites = sides.sites.map((site) => `${site.name}: ${siteOf(site, inner, siteWriting)}`);
  return [
    ...lines,
    `${indent}return $.client({`,
    `${inner}props: ${objectOf(props, inner)},`,
    `${inner}states: ${objectOf(states, inner)},`,
    `${inner}slots: ${objectOf(slots, inner)},`,
    // After the states, which the sites' functions are typed by.
    ...(sites.length === 0 ? [] : [`${inner}sites: ${objectOf(sites, inner)},`]),
    `${indent}});`,
  ];
}

/**
 * A site, as the authority runs it: the states the page sends for it — those its element reads, and
 * those its conditions read — the guard of the conditions it stands under, and its element, of the
 * states it reads; a list's items (`each`), of the states its array reads. Each function
 * destructures the states it reads, and no other.
 */
function siteOf(site: Site, indent: string, writing: SiteWriting): string {
  const { sourceFile } = writing.component;
  const { list } = site;
  const inputs = `inputs: [${site.sent.map((input) => literal(input.key)).join(', ')}]`;
  const body = (rewrite: Rewrite): string => {
    return list === undefined
      ? moved(site.element, indent, { rewrite, sourceFile })
      : itemsOf(site, list, { indent, rewrite, sourceFile });
  };
  const render = `${list === undefined ? 'render' : 'each'}: ${siteFunction(site.inputs, writing, body)}`;
  if (site.conditions.length === 0) {
    return `{ ${inputs}, ${render} }`;
  }
  const guard = siteFunction(site.guarded, writing, (rewrite) =>
    guardOf(site.conditions, (test) => moved(test, indent, { rewrite, sourceFile })),
  );
  return `{ ${inputs}, guard: ${guard}, ${render} }`;
}

/**
 * A list's items, as its `each` writes them: the array the browser maps, computed again of the
 * states it reads, mapped as the browser maps it — to each item's key, the item, and its element —
 * each item counted as it is made (`$.counted`), its key's text and the item with it.
 */
function itemsOf(
  site: Site,
  list: SiteList,
  at: { readonly indent: string; readonly rewrite: Rewrite; readonly sourceFile: SourceFile },
): string {
  const written = (node: Node): string => moved(node, at.indent, at);
  const array = accessed(list.array, written(list.array));
  const item = list.item.text;
  return `$.method(${array}, "map")((${item}) => $.counted({ item: ${item}, key: ${written(list.key)}, render: () => ${written(site.element)} }))`;
}

/** The names of a component's that only its Client Component holds, which its program does not. */
const BROWSER_NAMES: ReadonlySet<TopLevel['kind']> = new Set([
  'constant',
  'hooked',
  'setter',
  'state',
]);

/** What a site's functions are written with: the component, its derivations, and the program's imports. */
interface SiteWriting {
  readonly component: Component;
  readonly derivation: Derivation;
  readonly lines: ImportPlan;
  /** The names the program imports what the sites' values are computed by under. */
  readonly imports: readonly string[];
}

/**
 * A site's function of `inputs`: the inputs destructured — each of the component's own states by its
 * name, which the site's code reads it by, then each of a hook's by its name in the hook where that
 * is free — and its body, written by `body` with the rewrite of the code it is computed by.
 */
function siteFunction(
  inputs: readonly SiteInput[],
  writing: SiteWriting,
  body: (rewrite: Rewrite) => string,
): string {
  const { component, derivation } = writing;
  const aliases = new Map<string, string>();
  const used = new Set<string>();
  // The names the program's `evaluate` holds where a site's function runs — the props, the server
  // part's, the imports — and those the code written there declares or reads as globals; a name of
  // the browser's is none of the program's.
  const blocked = (name: string): boolean => {
    const entry = component.names.get(name);
    return (
      used.has(name) ||
      name === '$' ||
      OWN_NAMES.has(name) ||
      writing.imports.includes(name) ||
      derivation.taken.has(name) ||
      (entry !== undefined && !BROWSER_NAMES.has(entry.kind))
    );
  };
  for (const input of inputs) {
    if (input.state !== undefined) {
      aliases.set(input.key, input.key);
      used.add(input.key);
    }
  }
  for (const input of inputs) {
    if (input.state === undefined) {
      const alias = unusedName(input.local, blocked);
      aliases.set(input.key, alias);
      used.add(alias);
    }
  }
  const naming: Naming = {
    import: (binding) => writing.lines.require(binding),
    input: (key) => aliases.get(key) ?? key,
    type: (binding) => writing.lines.requireType(binding),
  };
  // A value read more than once is computed once, by a name of its own (`Held`).
  const held = new Held((wanted) => {
    const name = unusedName(wanted, blocked);
    used.add(name);
    return name;
  });
  body(siteRewrite(writing, held.counting(naming)));
  const parameter =
    inputs.length === 0
      ? '()'
      : `({ ${inputs
          .map((input) => {
            const alias = aliases.get(input.key) ?? input.key;
            return alias === input.key ? alias : `${literal(input.key)}: ${alias}`;
          })
          .join(', ')} })`;
  const holding = held.holding(naming);
  const written = body(siteRewrite(writing, holding));
  return `${parameter} => ${held.body(written)}`;
}

/**
 * The rewrite of a site's element and conditions: each value the browser computes, computed again
 * in place of what reads it (`derive.ts`), and each JSX node rendered as `$.h(…)`.
 */
function siteRewrite(writing: SiteWriting, naming: Naming): Rewrite {
  const { component, derivation } = writing;
  const { fail, sourceFile } = component;
  const rendering: Rendering = {
    expression: (node) => textOf(node, sourceFile, rewrite),
    fail,
    sourceFile,
    type: (tag) => typeOfTag(tag, fail),
  };
  const composed = derivation.rewrite({ kind: 'component' }, naming, (node) =>
    isJsx(node) ? rendered(node, rendering) : undefined,
  );
  function rewrite(node: Node): string | undefined {
    return composed(node);
  }
  return composed;
}

/** The text of `node`, its JSX rendered, its lines after the first indented from `indent`. */
function moved(
  node: Node,
  indent: string,
  context: { readonly rewrite: Rewrite; readonly sourceFile: SourceFile },
): string {
  const { rewrite, sourceFile } = context;
  return reindented(
    textOf(node, sourceFile, rewrite),
    indentAt(sourceFile.text, node.getStart(sourceFile)),
    indent,
  );
}

/** An object literal of `entries`: on one line where it is short, else one entry to a line. */
function objectOf(entries: readonly string[], indent: string): string {
  if (entries.length === 0) {
    return '{}';
  }
  const flat = `{ ${entries.join(', ')} }`;
  if (!flat.includes('\n') && indent.length + flat.length <= WIDTH) {
    return flat;
  }
  const inner = `${indent}  `;
  return [
    '{',
    ...entries.map((entry) => `${inner}${reindented(entry, indent, inner)},`),
    `${indent}}`,
  ].join('\n');
}

/** The rewrite of the authority's code: each JSX node rendered as `$.h(…)`. */
function renderingRewrite(component: Component): Rewrite {
  const { fail, sourceFile } = component;
  const rendering: Rendering = {
    expression: (node) => textOf(node, sourceFile, rewrite),
    fail,
    sourceFile,
    type: (tag) => typeOfTag(tag, fail),
  };
  function rewrite(node: Node): string | undefined {
    return isJsx(node) ? rendered(node, rendering) : undefined;
  }
  return rewrite;
}

/** Each updater's entry in `updaters`, its imports added to `lines`. */
function updaterEntries(input: AuthorityInput, lines: ImportPlan): readonly string[] {
  return [...input.updaters].map(([id, { keys, site }]) => {
    const listed = `keys: [${[...keys].map((key) => literal(key)).join(', ')}]`;
    if (site.kind === 'set') {
      return `${literal(id)}: { ${listed}, kind: "set" },`;
    }
    const [first = ''] = keys;
    return `${literal(id)}: { ${listed}, kind: "apply", apply: ${applyOf(site, first, lines)} },`;
  });
}

/** An update as the authority runs it: of the current value, typed, and of what its call captured. */
function applyOf(site: ApplySite, key: string, lines: ImportPlan): string {
  const { update } = site;
  const type = site.type ?? `States[${literal(key)}]`;
  const renames = new Map<string, string>();
  for (const binding of update.imports) {
    const local = lines.require(binding);
    if (local !== binding.name.text) {
      renames.set(binding.name.text, local);
    }
  }
  const parameters = [`${updaterParameter(update, renames)}: ${type}`];
  if (update.captures.length > 0) {
    const names = update.captures.map((capture) => capture.name).join(', ');
    const types = update.captures
      .map((capture) => `${propertyName(capture.name)}: ${capture.type}`)
      .join('; ');
    parameters.push(`{ ${names} }: { ${types} }`);
  }
  const body = textOf(update.fn.body, update.sourceFile, (node) => renamed(node, renames));
  const from = indentAt(update.sourceFile.text, update.fn.body.getStart(update.sourceFile));
  return `(${parameters.join(', ')}): ${type} => ${reindented(body, from, UPDATE_INDENT)}`;
}

/** An unused current-value parameter shadows no capture, local binding or renamed import. */
function updaterParameter(
  update: ApplySite['update'],
  renames: ReadonlyMap<string, string>,
): string {
  if (update.parameter !== undefined) {
    return update.parameter.text;
  }
  const taken = new Set(renames.values());
  const visit = (node: Node): void => {
    if (isIdentifier(node)) {
      taken.add(node.text);
    }
    node.forEachChild(visit);
  };
  visit(update.fn.body);
  return unusedName('_current', (name) => taken.has(name));
}

function renamed(node: Node, renames: ReadonlyMap<string, string>): string | undefined {
  // `{ LIMIT }` of an import read under another name: the entry keeps its key, `{ LIMIT: LIMIT$2 }`.
  if (
    isShorthandPropertyAssignment(node) &&
    isIdentifier(node.name) &&
    node.objectAssignmentInitializer === undefined
  ) {
    const local = renames.get(node.name.text);
    return local === undefined ? undefined : `${node.name.text}: ${local}`;
  }
  return isIdentifier(node) && readsBinding(node) ? renames.get(node.text) : undefined;
}
