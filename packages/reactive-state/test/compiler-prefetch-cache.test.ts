import { readFile } from 'node:fs/promises';
import path from 'node:path';

import type { API } from 'typescript/sync';
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';

import { givenHost } from '../src/compiler/host.ts';
import { type Compiled, compileApp, openTypeScript, writeOutputs } from '../src/compiler/index.ts';
import {
  loaderOptions,
  loaderOptionsOf,
  projectOfLoader,
  reactiveRule,
  withReactiveState,
} from '../src/next/config.ts';
import {
  application,
  type Application,
  cli,
  output,
  removed,
  typeCheck,
} from './fixtures/application.ts';

/**
 * Where the roots a link's prefetch carries are kept: in the browser alone (`--prefetch-cache
 * private`, the default, whose output is what it was before the option), or in the deployment's
 * cache too (`remote`), keyed by the reader's session, whose entry reads the session outside the
 * cache and renders the root inside `'use cache: remote'`. A root of a persistent state, its own or
 * a component's it renders, and a root of a route, stay private; every root of such a build hands
 * the page the `expire` Server Function, and each stub tells `operate` the build keeps its roots.
 */

// A whole compile of the fixture runs well past vitest's five seconds on a loaded machine.
vi.setConfig({ hookTimeout: 300_000, testTimeout: 300_000 });

interface Compile {
  readonly app: Application;
  readonly result: Compiled;
}

/** The application's session source, which the copy holds for the outputs to type-check. */
const SESSION_SOURCE = [
  "import type { SessionSource } from '@arkorlab/reactive-state/next';",
  '',
  'export const appSession: SessionSource = () => null;',
  '',
].join('\n');

/** The options of a build whose roots the deployment's cache keeps. */
const REMOTE = {
  prefetch: 'status',
  prefetchCache: 'remote',
  session: '@/session#appSession',
} as const;

/** `ProjectSummary`'s entry, of no state and no route, which the deployment's cache keeps. */
const SUMMARY_KEPT = [
  '// Generated by @arkorlab/reactive-state from components/project-summary.reactive.tsx. Do not edit: change the component and compile it again.',
  "import { cacheLife, cacheTag } from 'next/cache';",
  '',
  "import { keptRootTag, keptSessionOf, keptUserTag, renderRoot, requestSession } from '@arkorlab/reactive-state/next';",
  "import { elements } from '../elements';",
  "import { expire, update, view } from '../server-functions';",
  '',
  'export default async function ProjectSummary(props: { projectId: string }) {',
  '  const session = await keptSession();',
  '  return session === null',
  '    ? renderRoot({ component: "components/project-summary", elements, props, expire, update, view })',
  '    : kept(session, props);',
  '}',
  '',
  "/** The request's session, where the deployment's cache may keep its roots, and none where not: read inside a private cache, which a runtime prefetch includes, so that the session source's I/O and the clock are read there. */",
  'async function keptSession() {',
  "  'use cache: private';",
  '  cacheLife("status");',
  '  return keptSessionOf(await requestSession(elements.session));',
  '}',
  '',
  "/** The root as `session` sees it, kept in the deployment's cache by the session and the props: not exported, so that no caller names another session. */",
  'async function kept(session: Parameters<typeof keptRootTag>[0], props: { projectId: string }) {',
  "  'use cache: remote';",
  '  cacheLife("status");',
  '  cacheTag(await keptRootTag(session), await keptUserTag(session.user));',
  '  return renderRoot({ component: "components/project-summary", elements, props, session, prefetchable: true, expire, update, view });',
  '}',
  '',
].join('\n');

/** The Server Function a page expires its session's kept roots by, the route rendered again in its answer. */
const EXPIRE_FUNCTION = [
  '/**',
  " * The roots the deployment's cache keeps of the caller's session expired, and the route rendered",
  " * again in the same answer: what a page asks for in place of the router's refresh, for a session",
  " * that ended, changed or was refused. Of the request's own session and the others of its tag's",
  ' * bucket: it is given nothing, so no caller names another session.',
  ' */',
  'export async function expire(): Promise<void> {',
  '  await expireKeptRoots(elements.session);',
  '  refresh();',
  '}',
  '',
].join('\n');

/** The text of the first `'use server'` module's stub the compile wrote. */
function actionOf({ app, result }: Compile): string {
  for (const [file, text] of result.outputs) {
    if (path.relative(app.out, file).startsWith('actions')) {
      return text;
    }
  }
  throw new Error('The compile wrote no stub.');
}

/** What the compile refused, as each refusal says it. */
function refusalsOf(result: Compiled): readonly string[] {
  return result.refusals.map((refusal) => refusal.message);
}

describe('where the roots a prefetch carries are kept', () => {
  let api: API;
  const apps: Application[] = [];
  let remote: Compile;
  let told: Compile;
  let unsaid: Compile;
  /** The fixture compiled by the command line with `--prefetch-cache remote`. */
  let ran: { readonly status: number | null; readonly summary: string };

  async function compiled(options: Readonly<Record<string, string>>): Promise<Compile> {
    const app = await application({ 'session.ts': SESSION_SOURCE });
    apps.push(app);
    return {
      app,
      result: compileApp({ api, appDir: app.appDir, outDir: app.out, srcDir: app.src, ...options }),
    };
  }

  beforeAll(async () => {
    api = openTypeScript();
    remote = await compiled(REMOTE);
    told = await compiled({ ...REMOTE, prefetchCache: 'private' });
    unsaid = await compiled({ prefetch: 'status', session: '@/session#appSession' });
    const app = await application({ 'session.ts': SESSION_SOURCE });
    apps.push(app);
    const run = cli(
      app.src,
      '--out',
      app.out,
      '--app',
      app.appDir,
      '--session',
      '@/session#appSession',
      '--prefetch',
      'status',
      '--prefetch-cache',
      'remote',
    );
    ran = {
      status: run.status,
      summary:
        run.status === 0
          ? await readFile(path.join(app.out, 'components/project-summary.root.tsx'), 'utf8')
          : run.stderr,
    };
  });

  afterAll(async () => {
    api[Symbol.dispose]();
    for (const app of apps.splice(0)) {
      await removed(app);
    }
  });

  it('keeps a root of no state and no route in the deployment’s cache, by the session', () => {
    expect(refusalsOf(remote.result)).toStrictEqual([]);
    expect(output(remote.result, remote.app, 'components/project-summary.root.tsx')).toBe(
      SUMMARY_KEPT,
    );
  });

  it('tags every kept render by the session and by its user, for an access taken away', () => {
    for (const root of ['project-summary', 'project-access', 'project-commands']) {
      const entry = output(remote.result, remote.app, `components/${root}.root.tsx`);

      expect(entry).toContain(
        '  \'use cache: remote\';\n  cacheLife("status");\n  cacheTag(await keptRootTag(session), await keptUserTag(session.user));\n',
      );
    }
  });

  it('keys a root of node props by the props a page renders it with, typed as before', () => {
    const entry = output(remote.result, remote.app, 'components/project-access.root.tsx');
    const props = 'props: Omit<{\n  projectId: string;\n  children: ReactNode;\n}, "children">';

    expect(entry).toContain(`export default async function ProjectAccess(${props}) {`);
    expect(entry).toContain(
      `async function kept(session: Parameters<typeof keptRootTag>[0], ${props}) {`,
    );
    expect(entry).toContain("import type { ReactNode } from 'react';");
    expect(entry).not.toContain('export async function kept');
  });

  it('keeps a root of a persistent state private, and hands it the expiry', () => {
    const entry = output(remote.result, remote.app, 'components/todo-editor.root.tsx');

    expect(entry).toContain('  \'use cache: private\';\n  cacheLife("status");');
    expect(entry).toContain('prefetchable: true, expire, update, view });');
    expect(entry).toContain("import { expire, update, view } from '../server-functions';");
    expect(entry).not.toContain('use cache: remote');
  });

  it('keeps private a root that renders a component of a persistent state', () => {
    // The list holds no state of its own; each of its rows reads an item's fields.
    const entry = output(remote.result, remote.app, 'components/todo-list.root.tsx');

    expect(entry).toContain("'use cache: private';");
    expect(entry).not.toContain('use cache: remote');
  });

  it('keeps a root its route registers private: its render reads the request', () => {
    const entry = output(remote.result, remote.app, 'components/project.root.tsx');

    expect(entry).toContain("'use cache: private';");
    expect(entry).toContain(
      'route: "/projects/[projectId]", prefetchable: true, expire, update, view });',
    );
    expect(entry).not.toContain('use cache: remote');
  });

  it('hands the expiry to a root a shared route renders, which no cache keeps', () => {
    const entry = output(remote.result, remote.app, 'components/public-board.root.tsx');

    expect(entry).not.toContain('use cache');
    expect(entry).toContain('route: "/boards/[projectId]", expire, update, view });');
  });

  it('writes the Server Function a page expires its session’s kept roots by', () => {
    const functions = output(remote.result, remote.app, 'server-functions.ts');

    expect(functions).toContain(
      "import { expireKeptRoots, updateField, viewRoot, type ViewAnswer } from '@arkorlab/reactive-state/next';",
    );
    expect(functions).toContain("import { refresh } from 'next/cache';");
    expect(functions.endsWith(EXPIRE_FUNCTION)).toBe(true);
  });

  it('tells each stub’s operate that the build keeps its roots', () => {
    expect(actionOf(remote)).toContain(', session: session$, kept: true }) as Promise');
  });

  it('writes what it wrote before where the cache is private, said or not', () => {
    expect(refusalsOf(told.result)).toStrictEqual([]);
    expect([...told.result.outputs.values()]).toStrictEqual([...unsaid.result.outputs.values()]);
    expect(output(unsaid.result, unsaid.app, 'server-functions.ts')).not.toContain('expire');
    expect(actionOf(unsaid)).not.toContain('kept');
    expect(output(unsaid.result, unsaid.app, 'components/project-summary.root.tsx')).toContain(
      '  \'use cache: private\';\n  cacheLife("status");\n  return renderRoot({ component: "components/project-summary", elements, props, prefetchable: true, update, view });',
    );
  });

  it('writes outputs the application’s type check takes', () => {
    writeOutputs(remote.result.outputs, remote.app.out);
    const checked = typeCheck(remote.app);

    expect(checked.stdout + checked.stderr).toBe('');
  });

  it('is named by the command line’s --prefetch-cache', () => {
    expect(ran.status).toBe(0);
    expect(ran.summary).toBe(SUMMARY_KEPT);
  });

  it('refuses a remote cache where no prefetch names its lifetime', () => {
    const result = compileApp({
      api,
      appDir: 'app',
      outDir: '.reactive',
      prefetchCache: 'remote',
      session: '@/session#appSession',
      srcDir: 'src',
    });

    expect(refusalsOf(result)).toStrictEqual([
      expect.stringContaining(
        "`--prefetch-cache remote` keeps the roots a link's prefetch carries",
      ),
    ]);
    expect(result.refusals[0]?.fileName).toBe('--prefetch-cache');
  });

  it('refuses a remote cache of the demo’s sessions, whose key would be the cookie', () => {
    const result = compileApp({
      api,
      appDir: 'app',
      outDir: '.reactive',
      prefetch: 'status',
      prefetchCache: 'remote',
      srcDir: 'src',
    });

    expect(refusalsOf(result)).toStrictEqual([
      expect.stringContaining("the demo's session is its cookie's value"),
    ]);
    expect(result.refusals[0]?.message).toContain('--session');
  });

  it('refuses a cache it does not know', () => {
    const result = compileApp({
      api,
      appDir: 'app',
      outDir: '.reactive',
      prefetch: 'status',
      prefetchCache: 'public',
      session: '@/session#appSession',
      srcDir: 'src',
    });

    expect(refusalsOf(result)).toStrictEqual([
      expect.stringContaining('`public` is no prefetch cache: `private` or `remote`'),
    ]);
  });

  it('refuses on the command line too, before a source is read', () => {
    const { app } = told;
    const refused = cli(
      app.src,
      '--out',
      app.out,
      '--app',
      app.appDir,
      '--prefetch-cache',
      'remote',
    );

    expect(refused.status).toBe(1);
    expect(refused.stderr).toContain('`--prefetch-cache remote` keeps the roots');
  });

  it('is an option of withReactiveState, which the adapter reads of its rule, handed to the compile', () => {
    const options = {
      prefetch: 'minutes',
      prefetchCache: 'remote',
      session: '@/session#s',
    } as const;
    const loader = loaderOptions(options);

    expect(loader).toMatchObject(options);
    expect(loaderOptionsOf(reactiveRule(loader))).toMatchObject(options);
    expect(projectOfLoader(loader)).toMatchObject(options);
    expect(givenHost(projectOfLoader(loader))).toMatchObject(options);
    expect(withReactiveState({}, options)).toBeDefined();
    expect(loaderOptions({})).not.toHaveProperty('prefetchCache');
  });
});
