import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import process from 'node:process';

import { afterEach, describe, expect, it, vi } from 'vitest';

import { writeOutputs } from '../src/compiler/index.ts';

/**
 * What a write of the compile's outputs does with what an earlier build left: a file it wrote that
 * this build does not is stale, and a write removes it — and the directories it leaves empty — before
 * it writes anything. Where the file system keeps no case (macOS, Windows), a file of a name that
 * differs from an output's in case alone is that output's: a write over it updates it in place, under
 * the old spelling, and the scan that follows takes that spelling for a file the build no longer
 * writes and removes it, the write reporting success with the output gone. Removed first, an output
 * is written afresh under its own spelling. A check removes and writes nothing.
 *
 * A directory that cannot be read is no empty one: the scan of the stale files reports it, with its
 * path, where a check would otherwise pass over a file it could not see. One that is not there holds
 * none.
 *
 * The order of what is removed and what is written is read from the calls the module makes, which
 * holds on any file system; the rows that need one that keeps no case run where the temporary
 * directory is one.
 */

/** What the write calls of the module under test were, in order, while `logging` is on. */
const calls = vi.hoisted(() => ({ log: [] as string[], logging: false }));

vi.mock(import('node:fs'), async (importOriginal) => {
  const actual = await importOriginal();
  return {
    ...actual,
    rmSync: (...given: Parameters<typeof actual.rmSync>) => {
      if (calls.logging) {
        calls.log.push(`remove ${String(given[0])}`);
      }
      actual.rmSync(...given);
    },
    writeFileSync: (...given: Parameters<typeof actual.writeFileSync>) => {
      if (calls.logging) {
        calls.log.push(`write ${String(given[0])}`);
      }
      actual.writeFileSync(...given);
    },
  };
});

const dirs: string[] = [];

/** The first line of every file the compile writes. */
const HEADER =
  '// Generated by @arkorlab/reactive-state from components/Board.reactive.tsx. Do not edit';

/** A file the compile wrote, of `body`. */
const generated = (body: string): string =>
  `${HEADER}: change the component and compile it again.\n${body}\n`;

/** A directory of its own, and whether the file system under it keeps the case of a name. */
function workspace(): { readonly keepsCase: boolean; readonly root: string } {
  const root = mkdtempSync(path.join(tmpdir(), 'reactive-state-write-outputs-'));
  dirs.push(root);
  writeFileSync(path.join(root, 'probe'), '');
  return { keepsCase: !existsSync(path.join(root, 'PROBE')), root };
}

/** The names under `directory`, with their spelling on disk. */
function listing(directory: string): readonly string[] {
  return readdirSync(directory, { recursive: true })
    .map(String)
    .toSorted((a, b) => a.localeCompare(b));
}

/** The output directory of a build that left a stale file beside a directory nobody may read. */
function locked(): {
  readonly blocked: string;
  readonly outDir: string;
  readonly root: string;
} {
  const { root } = workspace();
  const outDir = path.join(root, '.reactive');
  const blocked = path.join(outDir, 'blocked');
  mkdirSync(blocked, { recursive: true });
  writeFileSync(path.join(outDir, 'Stale.authority.mts'), generated('stale'));
  chmodSync(blocked, 0o000);
  return { blocked, outDir, root };
}

/**
 * Whether a directory nobody may read is one here: not for the superuser, and not on a volume that
 * keeps no permissions of a directory (a Windows volume mounted under WSL), where a row about a
 * directory the scan cannot read has none to show.
 */
function unreadableHere(): boolean {
  if (process.getuid?.() === 0) {
    return false;
  }
  const probe = mkdtempSync(path.join(tmpdir(), 'reactive-state-permission-probe-'));
  const blocked = path.join(probe, 'blocked');
  try {
    mkdirSync(blocked);
    chmodSync(blocked, 0o000);
    readdirSync(blocked);
    return false;
  } catch {
    return true;
  } finally {
    chmodSync(blocked, 0o700);
    rmSync(probe, { force: true, recursive: true });
  }
}

const UNREADABLE = unreadableHere();

const CASE_INSENSITIVE = !workspace().keepsCase;

describe('what a write of the outputs does with the files an earlier build left', () => {
  afterEach(() => {
    calls.logging = false;
    calls.log.length = 0;
    for (const dir of dirs.splice(0)) {
      rmSync(dir, { force: true, recursive: true });
    }
  });

  describe('a file the build no longer writes is removed before the outputs are written', () => {
    it('the old spelling of an output goes first, and the output is written after it', () => {
      const { root } = workspace();
      const outDir = path.join(root, '.reactive');
      mkdirSync(path.join(outDir, 'components'), { recursive: true });
      const old = path.join(outDir, 'components/Board.authority.mts');
      writeFileSync(old, generated('before'));
      const output = path.join(outDir, 'components/board.authority.mts');
      calls.logging = true;

      const written = writeOutputs(new Map([[output, generated('after')]]), outDir);

      expect(calls.log).toStrictEqual([`remove ${old}`, `write ${output}`]);
      expect(
        written.map(({ leftover, path: file }) => [path.basename(file), leftover]),
      ).toStrictEqual([
        ['board.authority.mts', false],
        ['Board.authority.mts', true],
      ]);
      expect(readFileSync(output, 'utf8')).toBe(generated('after'));
    });

    it('the directories the removal leaves empty go with it, and one that holds another file stays', () => {
      const { root } = workspace();
      const outDir = path.join(root, '.reactive');
      mkdirSync(path.join(outDir, 'old/inner'), { recursive: true });
      mkdirSync(path.join(outDir, 'shared'), { recursive: true });
      writeFileSync(path.join(outDir, 'old/inner/Gone.authority.mts'), generated('gone'));
      writeFileSync(path.join(outDir, 'shared/Gone.authority.mts'), generated('gone'));
      writeFileSync(path.join(outDir, 'shared/notes.md'), 'a file of the application’s');

      writeOutputs(new Map([[path.join(outDir, 'kept.authority.mts'), generated('kept')]]), outDir);

      expect(listing(outDir)).toStrictEqual(['kept.authority.mts', 'shared', 'shared/notes.md']);
    });

    it('a directory the files of an earlier build were in does not block the file that takes its name', () => {
      const { root } = workspace();
      const outDir = path.join(root, '.reactive');
      mkdirSync(path.join(outDir, 'reports.ts'), { recursive: true });
      writeFileSync(path.join(outDir, 'reports.ts/Board.authority.mts'), generated('before'));
      const output = path.join(outDir, 'reports.ts');

      writeOutputs(new Map([[output, generated('after')]]), outDir);
      writeOutputs(new Map([[output, generated('after')]]), outDir);

      expect(listing(outDir)).toStrictEqual(['reports.ts']);
      expect(readFileSync(output, 'utf8')).toBe(generated('after'));
    });

    it('a directory that holds a file of the application’s stays, and the error names its path', () => {
      const { root } = workspace();
      const outDir = path.join(root, '.reactive');
      mkdirSync(path.join(outDir, 'reports.ts'), { recursive: true });
      writeFileSync(path.join(outDir, 'reports.ts/Board.authority.mts'), generated('before'));
      writeFileSync(path.join(outDir, 'reports.ts/notes.md'), 'a file of the application’s');
      const output = path.join(outDir, 'reports.ts');

      expect(() => writeOutputs(new Map([[output, generated('after')]]), outDir)).toThrow(output);
      expect(listing(outDir)).toStrictEqual(['reports.ts', 'reports.ts/notes.md']);
    });

    it('a check removes and writes nothing, and takes the old spelling for stale', () => {
      const { root } = workspace();
      const outDir = path.join(root, '.reactive');
      mkdirSync(path.join(outDir, 'components'), { recursive: true });
      writeFileSync(path.join(outDir, 'components/Board.authority.mts'), generated('before'));
      const output = path.join(outDir, 'components/board.authority.mts');
      calls.logging = true;

      const checked = writeOutputs(new Map([[output, generated('after')]]), outDir, {
        check: true,
      });

      expect(calls.log).toStrictEqual([]);
      expect(
        checked.filter(({ current }) => !current).map(({ path: file }) => path.basename(file)),
      ).toContain('Board.authority.mts');
      expect(readdirSync(path.join(outDir, 'components'))).toContain('Board.authority.mts');
    });
  });

  describe.skipIf(!CASE_INSENSITIVE)('where the file system keeps no case', () => {
    it('an output renamed in case alone is written under its new spelling, and is there', () => {
      const { root } = workspace();
      const outDir = path.join(root, '.reactive');
      writeOutputs(
        new Map([[path.join(outDir, 'components/Board.authority.mts'), generated('before')]]),
        outDir,
      );

      writeOutputs(
        new Map([[path.join(outDir, 'components/board.authority.mts'), generated('after')]]),
        outDir,
      );

      expect(listing(outDir)).toStrictEqual(['components', 'components/board.authority.mts']);
      expect(readFileSync(path.join(outDir, 'components/board.authority.mts'), 'utf8')).toBe(
        generated('after'),
      );
    });

    it('an output whose text is unchanged is there as well, under its new spelling', () => {
      const { root } = workspace();
      const outDir = path.join(root, '.reactive');
      writeOutputs(
        new Map([[path.join(outDir, 'Board.authority.mts'), generated('same')]]),
        outDir,
      );

      writeOutputs(
        new Map([[path.join(outDir, 'board.authority.mts'), generated('same')]]),
        outDir,
      );

      expect(listing(outDir)).toStrictEqual(['board.authority.mts']);
    });

    it('a directory renamed in case alone is created under its new spelling, and is checked clean', () => {
      const { root } = workspace();
      const outDir = path.join(root, '.reactive');
      writeOutputs(
        new Map([[path.join(outDir, 'Cards/Board.authority.mts'), generated('x')]]),
        outDir,
      );
      const outputs = new Map([[path.join(outDir, 'cards/Board.authority.mts'), generated('x')]]);

      writeOutputs(outputs, outDir);

      expect(listing(outDir)).toStrictEqual(['cards', 'cards/Board.authority.mts']);
      expect(
        writeOutputs(outputs, outDir, { check: true }).filter(({ current }) => !current),
      ).toStrictEqual([]);
    });
  });

  describe('a directory the scan cannot read is reported, with its path', () => {
    afterEach(() => {
      for (const dir of dirs) {
        for (const blocked of [path.join(dir, '.reactive/blocked')]) {
          if (existsSync(blocked)) {
            chmodSync(blocked, 0o700);
          }
        }
      }
    });

    it.skipIf(!UNREADABLE)('a check does not pass over it', () => {
      const { blocked, outDir } = locked();
      const output = new Map([[path.join(outDir, 'kept.authority.mts'), generated('kept')]]);

      expect(() => writeOutputs(output, outDir, { check: true })).toThrow(blocked);
    });

    it.skipIf(!UNREADABLE)('a write does not go on over it', () => {
      const { blocked, outDir } = locked();
      const output = new Map([[path.join(outDir, 'kept.authority.mts'), generated('kept')]]);

      expect(() => writeOutputs(output, outDir)).toThrow(blocked);
      expect(existsSync(path.join(outDir, 'kept.authority.mts'))).toBe(false);
    });

    it('an output directory that is not there holds none, and a check says every output is stale', () => {
      const { root } = workspace();
      const outDir = path.join(root, '.reactive');
      const output = new Map([[path.join(outDir, 'kept.authority.mts'), generated('kept')]]);

      const checked = writeOutputs(output, outDir, { check: true });

      expect(checked).toStrictEqual([
        { current: false, leftover: false, path: path.join(outDir, 'kept.authority.mts') },
      ]);
      expect(existsSync(outDir)).toBe(false);
    });
  });
});
