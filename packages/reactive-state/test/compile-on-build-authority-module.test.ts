import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import { afterEach, describe, expect, it, vi } from 'vitest';

import { writeAuthorityModule } from '../src/next/authority-module.ts';
import { compileProject } from '../src/next/compile-on-build.ts';

/**
 * A host that registers the authority's object the compile writes by a module of its own choosing
 * — the deployment host registers `.reactive/durable-object.mjs`, and bundles what that
 * names — says so in `REACTIVE_AUTHORITY_MODULE` as it builds: a compile of another `out` writes a
 * module there that re-exports the class, and never writes over a file of the application's.
 */

const VARIABLE = 'REACTIVE_AUTHORITY_MODULE';
const DECLARED = '.reactive/durable-object.mjs';
const HOST = { [VARIABLE]: DECLARED };
const GENERATED = '// Generated by @arkorlab/reactive-state';
/** What the application keeps of its own where the host would import the object from. */
const OWN = 'export class ReactiveAuthority {}\n';

const HELLO = [
  'export default function Hello({ name }: { readonly name: string }) {',
  '  return <p>Hello, {name}</p>;',
  '}',
  '',
].join('\n');
const PAGE = [
  "import Hello from '@/components/hello.reactive';",
  '',
  'export default function Page() {',
  '  return <Hello name="world" />;',
  '}',
  '',
].join('\n');

const projects: string[] = [];

function project(): string {
  const dir = mkdtempSync(path.join(tmpdir(), 'reactive-state-authority-module-'));
  projects.push(dir);
  return dir;
}

function write(dir: string, file: string, text: string): void {
  mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
  writeFileSync(path.join(dir, file), text);
}

/** An application of one component and its page, as a build compiles it. */
function application(files: Readonly<Record<string, string>> = {}): string {
  const dir = project();
  const all = {
    'src/app/page.tsx': PAGE,
    'src/components/hello.reactive.tsx': HELLO,
    'tsconfig.json': JSON.stringify({
      compilerOptions: { jsx: 'react-jsx', paths: { '@/*': ['./src/*'] } },
    }),
    ...files,
  };
  for (const [file, text] of Object.entries(all)) write(dir, file, text);
  return dir;
}

function read(dir: string, file: string): string {
  return readFileSync(path.join(dir, file), 'utf8');
}

function cleanUp(): void {
  vi.unstubAllEnvs();
  for (const dir of projects.splice(0)) rmSync(dir, { force: true, recursive: true });
}

describe('writeAuthorityModule', () => {
  afterEach(cleanUp);

  it('writes, where the host imports the object from, a module that re-exports it from the `out` the compile wrote it into', async () => {
    const dir = project();
    const outDir = path.join(dir, 'generated');
    write(dir, 'generated/durable-object.mjs', 'export const ReactiveAuthority = class {};\n');

    const changed = writeAuthorityModule({ projectDir: dir, outDir }, HOST);
    const written = read(dir, DECLARED);
    const [compiled, reexported] = await Promise.all([
      import(pathToFileURL(path.join(outDir, 'durable-object.mjs')).href),
      import(pathToFileURL(path.join(dir, DECLARED)).href),
    ]);

    expect(changed).toBe(true);
    expect(written.startsWith(GENERATED)).toBe(true);
    expect(written.split('\n').slice(1)).toStrictEqual([
      "export { ReactiveAuthority } from '../generated/durable-object.mjs';",
      '',
    ]);
    expect(Object.keys(reexported as Record<string, unknown>)).toStrictEqual(['ReactiveAuthority']);
    expect((reexported as Record<string, unknown>)['ReactiveAuthority']).toBe(
      (compiled as Record<string, unknown>)['ReactiveAuthority'],
    );
  });

  it('finds the object in an `out` nested anywhere under the root', () => {
    const dir = project();

    writeAuthorityModule({ projectDir: dir, outDir: path.join(dir, 'build/reactive') }, HOST);

    expect(read(dir, DECLARED)).toContain(
      "export { ReactiveAuthority } from '../build/reactive/durable-object.mjs';",
    );
  });

  it('writes nothing of the default `out`, where the compile writes the object itself, nor where no host says where it imports it from', () => {
    const dir = project();
    const placed = { projectDir: dir, outDir: path.join(dir, '.reactive') };
    const custom = { projectDir: dir, outDir: path.join(dir, 'generated') };

    expect(writeAuthorityModule(placed, HOST)).toBe(false);
    expect(writeAuthorityModule(custom, {})).toBe(false);
    expect(writeAuthorityModule(custom, { [VARIABLE]: '' })).toBe(false);
    expect(existsSync(path.join(dir, '.reactive'))).toBe(false);
  });

  it('writes nothing where a link there leads to the object the compile writes', () => {
    const dir = project();
    write(dir, 'generated/durable-object.mjs', 'export const ReactiveAuthority = class {};\n');
    symlinkSync(path.join(dir, 'generated'), path.join(dir, '.reactive'));

    expect(
      writeAuthorityModule({ projectDir: dir, outDir: path.join(dir, 'generated') }, HOST),
    ).toBe(false);
    expect(read(dir, 'generated/durable-object.mjs')).toBe(
      'export const ReactiveAuthority = class {};\n',
    );
  });

  it('refuses to write over a file of the application’s there, and leaves it as it is', () => {
    const dir = project();
    write(dir, DECLARED, OWN);

    expect(() =>
      writeAuthorityModule({ projectDir: dir, outDir: path.join(dir, 'generated') }, HOST),
    ).toThrow(
      `REACTIVE_AUTHORITY_MODULE names \`${DECLARED}\`, where the host imports the authority's object from, and the application has a file of its own there`,
    );
    expect(read(dir, DECLARED)).toBe(OWN);
  });

  it('writes over what a compile wrote there — an earlier one’s object, of the default `out` — and leaves what it wrote as it is', () => {
    const dir = project();
    const placed = { projectDir: dir, outDir: path.join(dir, 'generated') };
    write(dir, DECLARED, `${GENERATED} from the application's components.\nexport const x = 1;\n`);

    const replaced = writeAuthorityModule(placed, HOST);
    const again = writeAuthorityModule(placed, HOST);

    expect(replaced).toBe(true);
    expect(again).toBe(false);
    expect(read(dir, DECLARED)).toContain(
      "export { ReactiveAuthority } from '../generated/durable-object.mjs';",
    );
  });

  it.each(['../elsewhere/durable-object.mjs', '/srv/app/durable-object.mjs', '.'])(
    'refuses a path that names no file under the application’s root: %s',
    (declared) => {
      const dir = project();

      expect(() => {
        return writeAuthorityModule(
          { projectDir: dir, outDir: path.join(dir, 'generated') },
          { [VARIABLE]: declared },
        );
      }).toThrow(`REACTIVE_AUTHORITY_MODULE is \`${declared}\``);
    },
  );
});

describe('compileProject where a host imports the authority’s object from a module of its own', () => {
  afterEach(cleanUp);

  it('writes the module that re-exports it of a compile of another `out`, and again where it is taken away, whether it compiles or not', async () => {
    vi.stubEnv(VARIABLE, DECLARED);
    const dir = application();

    const first = await compileProject({ out: 'generated', projectDir: dir });
    const written = read(dir, DECLARED);
    rmSync(path.join(dir, DECLARED));
    const again = await compileProject({ out: 'generated', projectDir: dir });
    const kept = await compileProject({ out: 'generated', projectDir: dir });

    expect(first).toMatchObject({ changed: true, compiled: true });
    expect(read(dir, 'generated/durable-object.mjs')).toContain(
      'export const ReactiveAuthority = authorityObject(application);',
    );
    expect(written).toContain(
      "export { ReactiveAuthority } from '../generated/durable-object.mjs';",
    );
    expect(again).toMatchObject({ changed: true, compiled: false });
    expect(read(dir, DECLARED)).toBe(written);
    expect(kept).toMatchObject({ changed: false, compiled: false });
  });

  it('writes the object there itself of the default `out`, and nothing else', async () => {
    vi.stubEnv(VARIABLE, DECLARED);
    const dir = application();

    await compileProject({ projectDir: dir });

    expect(read(dir, DECLARED)).toContain(
      'export const ReactiveAuthority = authorityObject(application);',
    );
  });

  it('refuses where the application has a file of its own there', async () => {
    vi.stubEnv(VARIABLE, DECLARED);
    const dir = application({ [DECLARED]: OWN });

    await expect(compileProject({ out: 'generated', projectDir: dir })).rejects.toThrow(
      'which @arkorlab/reactive-state does not write over',
    );
    expect(read(dir, DECLARED)).toBe(OWN);
  });

  it('writes nothing where no host says it imports the object from a module of its own', async () => {
    vi.stubEnv(VARIABLE, undefined);
    const dir = application();

    await compileProject({ out: 'generated', projectDir: dir });

    expect(existsSync(path.join(dir, '.reactive'))).toBe(false);
  });
});
