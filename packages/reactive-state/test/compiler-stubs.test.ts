import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import type { API } from 'typescript/sync';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import { type Compiled, openTypeScript, writeOutputs } from '../src/compiler/index.ts';
import {
  application,
  type Application,
  compiledApp,
  output,
  removed,
  source,
  variant,
} from './fixtures/application.ts';

/**
 * The stub of a `'use server'` module — what a page and a Client Component call in its place — typed
 * as the module's own operations, through an import of its types alone: a form's action bound of
 * one (`<form action={publishBoard.bind(null, projectId)}>`) is checked as the original would be,
 * and the stub still asks the authority to run the original, by its module and its name.
 */

const PACKAGE = fileURLToPath(new URL('../', import.meta.url));

const SETTINGS = 'components/publication-settings.reactive.tsx';
const COMMANDS = 'components/project-commands.reactive.tsx';

/** A source file of `lines`. */
function file(...lines: readonly string[]): string {
  return `${lines.join('\n')}\n`;
}

/** What the application's type check says of the files the compile wrote, and of no other. */
function diagnosticsOfOutputs(app: Application): readonly string[] {
  const tsc = path.join(PACKAGE, 'node_modules/typescript/bin/tsc');
  const ran = spawnSync(process.execPath, [tsc, '--noEmit', '-p', app.root], {
    cwd: app.root,
    encoding: 'utf8',
  });
  return `${ran.stdout}${ran.stderr}`
    .split('\n')
    .filter((line) => line.startsWith('.reactive/') || line.startsWith('src/'));
}

describe('the stubs of the application’s server operations', () => {
  let api: API;
  const apps: Application[] = [];

  beforeAll(() => {
    api = openTypeScript();
  });

  afterAll(async () => {
    api[Symbol.dispose]();
    for (const each of apps) {
      await removed(each);
    }
  });

  async function compiledWith(
    files: Readonly<Record<string, string>> = {},
  ): Promise<{ app: Application; compiled: Compiled }> {
    const app = await application(files);
    apps.push(app);
    return { app, compiled: compiledApp(app, api) };
  }

  it('types each stub as the operation it runs, through an import of the module’s types alone', async () => {
    const { app, compiled } = await compiledWith();

    expect(compiled.refusals).toStrictEqual([]);
    expect(
      output(compiled, app, 'actions/publication.ts').replaceAll(compiled.buildId, 'b_BUILD'),
    ).toBe(
      file(
        '// Generated by @arkorlab/reactive-state from actions/publication.ts. Do not edit: change the module and compile it again.',
        "'use server';",
        '',
        "import { operate } from '@arkorlab/reactive-state/next';",
        "import type * as source from '@/actions/publication';",
        '',
        'export async function publishBoard(...args: Parameters<typeof source.publishBoard>): Promise<Awaited<ReturnType<typeof source.publishBoard>>> {',
        '  return operate("actions/publication", "publishBoard", args, "b_BUILD") as Promise<Awaited<ReturnType<typeof source.publishBoard>>>;',
        '}',
        '',
        'export async function withdrawBoard(...args: Parameters<typeof source.withdrawBoard>): Promise<Awaited<ReturnType<typeof source.withdrawBoard>>> {',
        '  return operate("actions/publication", "withdrawBoard", args, "b_BUILD") as Promise<Awaited<ReturnType<typeof source.withdrawBoard>>>;',
        '}',
      ),
    );
  });

  it('writes a Client Component whose forms bind a stub as their action, which the type check accepts', async () => {
    const { app, compiled } = await compiledWith();
    writeOutputs(compiled.outputs, app.out);

    expect(output(compiled, app, 'components/publication-settings.client.tsx')).toContain(
      '<form action={publishBoard.bind(null, projectId)}>',
    );
    expect(diagnosticsOfOutputs(app)).toStrictEqual([]);
  });

  it('hands a Client Component an operation as a prop, bound, which the type check accepts', async () => {
    const completer = file(
      "'use client';",
      '',
      "import type { ReactNode } from 'react';",
      '',
      'export function Completer({ complete }: { readonly complete: () => Promise<void> }): ReactNode {',
      '  return (',
      '    <button type="button" onClick={() => void complete()}>',
      '      すべて完了にする',
      '    </button>',
      '  );',
      '}',
    );
    const commands = variant(
      variant(
        await source(COMMANDS),
        "import { createTodo, completeProject } from '@/actions/todos';",
        "import { createTodo, completeProject } from '@/actions/todos';\nimport { Completer } from '@/controls/completer';",
      ),
      '      <form action={completeProject.bind(null, projectId)}>\n        <button type="submit">すべて完了にする</button>\n      </form>',
      '      <Completer complete={completeProject.bind(null, projectId)} />',
    );
    const { app, compiled } = await compiledWith({
      'controls/completer.tsx': completer,
      [COMMANDS]: commands,
    });
    writeOutputs(compiled.outputs, app.out);

    expect(compiled.refusals).toStrictEqual([]);
    expect(output(compiled, app, 'components/project-commands.authority.mts')).toContain(
      '$.h(Completer, { complete: completeProject.bind(null, projectId) })',
    );
    expect(diagnosticsOfOutputs(app)).toStrictEqual([]);
  });

  it('names the module’s types by a name none of its exports takes, a default export’s among them', async () => {
    const renaming = file(
      "'use server';",
      '',
      "import { db } from '@/db';",
      '',
      'export async function source(projectId: string): Promise<void> {',
      "  await db.projects.update(projectId, { title: 'source' });",
      '}',
      '',
      'export default async function rename(projectId: string, title: string): Promise<number> {',
      '  await db.projects.update(projectId, { title });',
      '  return title.length;',
      '}',
    );
    const settings = variant(
      variant(
        await source(SETTINGS),
        "import { publishBoard, withdrawBoard } from '@/actions/publication';",
        "import { publishBoard, withdrawBoard } from '@/actions/publication';\nimport rename, { source } from '@/actions/renaming';",
      ),
      '<form action={publishBoard.bind(null, projectId)}>',
      '<form action={source.bind(null, projectId)}>\n        <button type="button" onClick={() => void rename(projectId, title)}>改名</button>\n      </form>\n      <form action={publishBoard.bind(null, projectId)}>',
    );
    const { app, compiled } = await compiledWith({
      'actions/renaming.ts': renaming,
      [SETTINGS]: settings,
    });
    const stub = output(compiled, app, 'actions/renaming.ts');
    writeOutputs(compiled.outputs, app.out);

    expect(compiled.refusals).toStrictEqual([]);
    expect(stub).toContain("import type * as source$2 from '@/actions/renaming';");
    expect(stub).toContain(
      'export async function source(...args: Parameters<typeof source$2.source>): Promise<Awaited<ReturnType<typeof source$2.source>>> {',
    );
    expect(stub).toContain(
      'export default async function operation(...args: Parameters<typeof source$2.default>): Promise<Awaited<ReturnType<typeof source$2.default>>> {',
    );
    expect(diagnosticsOfOutputs(app)).toStrictEqual([]);
  });
});
